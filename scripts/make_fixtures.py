def main(out_dir: str) -> None:
    os.makedirs(out_dir, exist_ok=True)
    n = 0
    lines = []
    for sid, _en, _ar, _ill in SLICES:
        rows = ROWS[sid]
        assert len(rows) == 10, (sid, len(rows))
        for ar, en in rows:
            n += 1
            ar_n, en_n = unicodedata.normalize("NFC", ar), unicodedata.normalize("NFC", en)
            assert ar_n == ar and en_n == en, f"row {n} is not NFC"
            lines.append(json.dumps({"row_id": f"fx{n:03d}", "slice": sid, "text_ar": ar, "text_en": en}, ensure_ascii=False))
    with open(os.path.join(out_dir, "fixtures.jsonl"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    slices = [{"slice": s, "label_en": en, "label_ar": ar, "illustrative": ill, "rows": 10} for s, en, ar, ill in SLICES]
    with open(os.path.join(out_dir, "slices.json"), "w", encoding="utf-8", newline="\n") as f:
        json.dump(slices, f, ensure_ascii=False, indent=1)
        f.write("\n")
    print(f"{n} fixtures written")


if __name__ == "__main__":
    main(sys.argv[1])
